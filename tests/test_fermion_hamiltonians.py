def test_density_density_matrix():
    V = 2.3

    model = make_model(neff=3, nf=2)

    n0 = edf.number(0)
    n1 = edf.number(1)

    H = edf.hamiltonian(V * n0 * n1).array

    # Basis:
    #   3 = 011 -> modes 0,1 occupied
    #   5 = 101 -> modes 0,2 occupied
    #   6 = 110 -> modes 1,2 occupied
    assert model.fockspace.ls == [3, 5, 6]

    expected = np.diag([V, 0.0, 0.0])

    np.testing.assert_allclose(H, expected, atol=1e-6)


# ---------------------------------------------------------------------------
# Two-site spinful Hubbard model
# ---------------------------------------------------------------------------

def build_two_site_hubbard(t, U):
    """
    Effective-mode ordering generated by EDinPy:

        mode 0 = (site 0, spin 0)
        mode 1 = (site 1, spin 0)
        mode 2 = (site 0, spin 1)
        mode 3 = (site 1, spin 1)
    """
    edf.clear()

    edf.DoF(2, name="site")
    edf.DoF(2, name="spin")

    model = edf.model(2)

    c00 = edf.operator([0, 0])
    c10 = edf.operator([1, 0])
    c01 = edf.operator([0, 1])
    c11 = edf.operator([1, 1])

    hopping = -t * (
        c00.dag * c10
        + c10.dag * c00
        + c01.dag * c11
        + c11.dag * c01
    )

    interaction = U * (
        edf.number([0, 0]) * edf.number([0, 1])
        + edf.number([1, 0]) * edf.number([1, 1])
    )

    return model, edf.hamiltonian(hopping + interaction)


def reference_two_site_hubbard(model, t, U):
    """
    Construct the same Hamiltonian independently using integer Fock states,
    bit operations, and the canonical fermionic sign.
    """
    basis = model.fockspace.ls
    index = {state: i for i, state in enumerate(basis)}

    H = np.zeros((len(basis), len(basis)), dtype=complex)

    # mode = site + 2 * spin
    for col, state in enumerate(basis):

        # Hopping for each spin.
        for spin in (0, 1):
            mode0 = 0 + 2 * spin
            mode1 = 1 + 2 * spin

            for destination, source in (
                (mode0, mode1),
                (mode1, mode0),
            ):
                result = hop(state, destination, source)

                if result is not None:
                    new_state, sign = result
                    row = index[new_state]
                    H[row, col] += -t * sign

        # On-site Hubbard interaction.
        for site in (0, 1):
            up = site
            down = site + 2

            if (
                state & (1 << up)
                and state & (1 << down)
            ):
                H[col, col] += U

    return H


def test_two_site_hubbard_matrix_matches_independent_reference():
    t = 1.3
    U = 4.2

    model, hamiltonian = build_two_site_hubbard(t=t, U=U)

    calculated = hamiltonian.array
    expected = reference_two_site_hubbard(model, t=t, U=U)

    assert model.fockspace.ls == [3, 5, 6, 9, 10, 12]

    np.testing.assert_allclose(
        calculated,
        expected,
        atol=1e-6,
    )

    np.testing.assert_allclose(
        calculated,
        calculated.conjugate().T,
        atol=1e-6,
    )


def test_two_site_hubbard_analytic_spectrum():
    """
    Half-filled two-site Hubbard model:

        E = (U - sqrt(U^2 + 16 t^2))/2
        E = 0                        (triplet, threefold)
        E = U
        E = (U + sqrt(U^2 + 16 t^2))/2
    """
    t = 1.3
    U = 4.2

    _, hamiltonian = build_two_site_hubbard(t=t, U=U)

    eigvals = np.linalg.eigvalsh(hamiltonian.array)

    root = np.sqrt(U**2 + 16.0 * t**2)

    expected = np.array(
        [
            0.5 * (U - root),
            0.0,
            0.0,
            0.0,
            U,
            0.5 * (U + root),
        ]
    )

    np.testing.assert_allclose(
        np.sort(eigvals),
        np.sort(expected),
        atol=1e-6,
    )


