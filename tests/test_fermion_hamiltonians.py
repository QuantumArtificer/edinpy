def test_dense_eigsolve_returns_requested_eigenpairs():
    """
    Verify the public dense eigensolver path, not merely NumPy applied
    externally to H.array.
    """
    t = 1.3
    U = 4.2

    _, hamiltonian = build_two_site_hubbard(t=t, U=U)

    hamiltonian.eigsolve(
        sparse=False,
        numeigs=2,
    )

    assert hamiltonian.eigvals.shape == (2,)
    assert hamiltonian.eigvecs.shape == (6, 2)

    reference = np.linalg.eigvalsh(hamiltonian.array)[:2]

    np.testing.assert_allclose(
        hamiltonian.eigvals,
        reference,
        atol=1e-6,
    )


def test_sparse_eigsolve_matches_dense_reference():
    t = 1.3
    U = 4.2

    _, hamiltonian = build_two_site_hubbard(t=t, U=U)

    reference = np.linalg.eigvalsh(hamiltonian.array)[:2]

    hamiltonian.eigsolve(
        sparse=True,
        numeigs=2,
        which="SA",
    )

    assert hamiltonian.eigvals.shape == (2,)
    assert hamiltonian.eigvecs.shape == (6, 2)

    np.testing.assert_allclose(
        np.sort(hamiltonian.eigvals),
        np.sort(reference),
        atol=1e-6,
    )


def test_nonhermitian_operator_matrix_is_preserved():
    """
    Matrix construction must represent the supplied operator directly rather
    than imposing Hermiticity.

    For basis [|10>, |01>] in EDinPy integer ordering,

        c_0^dagger c_1

    has only one nonzero matrix element.
    """
    make_model(neff=2, nf=1)

    c0 = edf.operator(0)
    c1 = edf.operator(1)

    H = edf.hamiltonian(c0.dag * c1).array

    expected = np.array(
        [
            [0.0, 1.0],
            [0.0, 0.0],
        ],
        dtype=complex,
    )

    np.testing.assert_allclose(H, expected, atol=1e-6)


def test_lowering_recognizes_number_and_hopping_terms():
    from edinpy.fermion._execution import compile_operator

    make_model(neff=4, nf=2)

    c0 = edf.Annihilation(0)
    c1 = edf.Annihilation(1)

    expression = (
        2.0 * edf.Number(0) * edf.Number(1)
        + 3.0 * c0.dag * c1
        + 3.0 * c1.dag * c0
    )

    compiled = compile_operator(expression)

    assert compiled.stats == {
        "number_product": 1,
        "hopping": 2,
        "hopping_groups": 1,
        "monomial": 0,
        "generic": 0,
    }


def test_lowering_specializes_four_fermion_monomial():
    """Verify that a four-fermion transition is lowered and remains correct."""
    from edinpy.fermion._execution import compile_operator

    model = make_model(neff=4, nf=2)
    c = [edf.Annihilation(i) for i in range(4)]

    term = c[0].dag * c[1].dag * c[3] * c[2]
    compiled = compile_operator(term)

    assert compiled.stats == {
        "number_product": 0,
        "hopping": 0,
        "hopping_groups": 0,
        "monomial": 1,
        "generic": 0,
    }
    assert compiled.fully_lowered

    H = edf.hamiltonian(term).array
    expected = np.zeros_like(H, dtype=complex)
    basis = model.fockspace.ls
    index = {state: i for i, state in enumerate(basis)}

    for col, state in enumerate(basis):
        amplitude = 1
        current = state

        for kind, site in (
            ("annihilate", 2),
            ("annihilate", 3),
            ("create", 1),
            ("create", 0),
        ):
            result = (
                annihilate(current, site)
                if kind == "annihilate"
                else create(current, site)
            )
            if result is None:
                amplitude = 0
                break
            current, sign = result
            amplitude *= sign

        if amplitude and current in index:
            expected[index[current], col] += amplitude

    np.testing.assert_allclose(H, expected, atol=1e-6)

def test_lowered_hopping_matches_independent_reference_exhaustively():
    """
    Verify direct lowered c_i^dagger c_j kernels for every pair of modes
    and every occupation state of a four-mode local Fock space.
    """
    from edinpy.fermion._execution import compile_operator

    neff = 4
    make_model(neff=neff, nf=2)

    for destination in range(neff):
        for source in range(neff):
            term = (
                edf.Annihilation(destination).dag
                * edf.Annihilation(source)
            )

            compiled = compile_operator(term)

            for state in range(1 << neff):
                ket_state = (
                    edf.vacuum()
                    if state == 0
                    else edf.fockstate(state)
                )

                calculated = compiled.apply(ket_state)

                if destination == source:
                    if state & (1 << source):
                        expected = {state: 1.0}
                    else:
                        expected = {}
                else:
                    reference = hop(
                        state,
                        destination,
                        source,
                    )

                    if reference is None:
                        expected = {}
                    else:
                        final_state, sign = reference
                        expected = {final_state: sign}

                assert set(calculated) == set(expected)

                for final_state, amplitude in expected.items():
                    assert np.isclose(
                        calculated[final_state],
                        amplitude,
                    )


def test_compiler_reports_fully_lowered_status():
    from edinpy.fermion._execution import compile_operator

    make_model(neff=4, nf=2)

    c0 = edf.Annihilation(0)
    c1 = edf.Annihilation(1)
    c2 = edf.Annihilation(2)
    c3 = edf.Annihilation(3)

    lowered = compile_operator(
        c0.dag * c1
        + 2.0 * edf.Number(0) * edf.Number(1)
    )

    quartic = compile_operator(
        c0.dag * c1.dag * c3 * c2
    )
    generic = compile_operator(
        edf.Number(0) * c1.dag * c2
    )

    assert lowered.fully_lowered
    assert quartic.fully_lowered
    assert not generic.fully_lowered


def test_direct_sparse_emission_matches_apply():
    from edinpy.fermion._execution import compile_operator

    model = make_model(neff=4, nf=2)

    c = [edf.Annihilation(i) for i in range(4)]

    expression = (
        -1.3 * (c[0].dag * c[1] + c[1].dag * c[0])
        + 0.7 * (c[2].dag * c[3] + c[3].dag * c[2])
        + 2.1 * edf.Number(0) * edf.Number(2)
    )

    compiled = compile_operator(expression)
    assert compiled.fully_lowered

    rows = []
    columns = []
    data = []

    expected = np.zeros(
        (model.Nbasis, model.Nbasis),
        dtype=complex,
    )

    basis = model.fockspace.ls
    index = {state: i for i, state in enumerate(basis)}

    for column, ket_state in enumerate(model.fockspace.basis):
        compiled.emit_sparse(
            ket_state,
            column,
            basis,
            model.Nbasis,
            rows,
            columns,
            data,
        )

        for state, amplitude in compiled.apply(ket_state).items():
            expected[index[state], column] += amplitude

    calculated = np.zeros_like(expected)

    for row, column, amplitude in zip(rows, columns, data):
        calculated[row, column] += amplitude

    np.testing.assert_allclose(
        calculated,
        expected,
        atol=1e-6,
    )


def test_lowered_monomials_match_reference_exhaustively():
    """Check general monomial kernels against sequential fermion algebra."""
    from edinpy.fermion._execution import compile_operator

    neff = 4
    make_model(neff=neff, nf=2)
    c = [edf.Annihilation(i) for i in range(neff)]

    terms_and_operations = [
        (
            c[0].dag * c[1].dag * c[3] * c[2],
            (
                ("annihilate", 2),
                ("annihilate", 3),
                ("create", 1),
                ("create", 0),
            ),
        ),
        (
            c[3].dag * c[0].dag * c[2] * c[1],
            (
                ("annihilate", 1),
                ("annihilate", 2),
                ("create", 0),
                ("create", 3),
            ),
        ),
        (
            c[0].dag * c[2].dag,
            (("create", 2), ("create", 0)),
        ),
        (
            c[3] * c[1],
            (("annihilate", 1), ("annihilate", 3)),
        ),
    ]

    for term, operations in terms_and_operations:
        compiled = compile_operator(term)
        assert compiled.stats["monomial"] == 1
        assert compiled.fully_lowered

        for state in range(1 << neff):
            ket_state = edf.vacuum() if state == 0 else edf.fockstate(state)
            calculated = compiled.apply(ket_state)

            current = state
            amplitude = 1

            for kind, site in operations:
                result = (
                    annihilate(current, site)
                    if kind == "annihilate"
                    else create(current, site)
                )
                if result is None:
                    amplitude = 0
                    break
                current, sign = result
                amplitude *= sign

            expected = {current: amplitude} if amplitude else {}
            assert set(calculated) == set(expected)

            for final_state, expected_amp in expected.items():
                assert np.isclose(
                    calculated[final_state],
                    expected_amp,
                )


def test_generic_fallback_is_preserved_for_mixed_products():
    """Mixed Number/fermion products retain the symbolic fallback path."""
    from edinpy.fermion._execution import compile_operator

    make_model(neff=4, nf=2)

    c1 = edf.Annihilation(1)
    c2 = edf.Annihilation(2)
    term = edf.Number(0) * c1.dag * c2
    compiled = compile_operator(term)

    assert compiled.stats == {
        "number_product": 0,
        "hopping": 0,
        "hopping_groups": 0,
        "monomial": 0,
        "generic": 1,
    }
    assert not compiled.fully_lowered

    for state in range(1 << 4):
        ket_state = edf.vacuum() if state == 0 else edf.fockstate(state)
        calculated = compiled.apply(ket_state)
        direct = term * ket_state

        if isinstance(direct, edf.null):
            expected = {}
        elif isinstance(direct, edf.fockstate):
            expected = {direct.state: complex(direct.amp)}
        elif isinstance(direct, edf.statesum):
            expected = {}
            for result_state in direct.states:
                expected[result_state.state] = (
                    expected.get(result_state.state, 0.0j)
                    + complex(result_state.amp)
                )
        else:
            raise TypeError(type(direct))

        assert set(calculated) == set(expected)
        for final_state, expected_amp in expected.items():
            assert np.isclose(
                calculated[final_state],
                expected_amp,
            )


